THICKEN = 0.0  # mm; nothing in this glyph is thinner than 1.2 mm at this size
CLOSE = 0.4  # softens the inside of the curl
ROUND = 0.4  # blunts the outer corners
COUNTER = 1.5  # mm, the island minimum for any counter (this glyph has none)
SCALE = 1.0  # the glyph already fits the reach above the centre of mass


def _fill(contours):
    """Even-odd fill of the contours: outer rings become the glyph, rings inside them become its counters."""
    return functools.reduce(lambda a, b: a.symmetric_difference(b), (Polygon(c).buffer(0) for c in contours))


def _open_counters(glyph):
    """Trim every counter to what can stand: each hole is replaced by its opening at the island minimum, so no sliver of face is left inside the cut."""
    polys = list(glyph.geoms) if isinstance(glyph, MultiPolygon) else [glyph]
    out = []
    for p in polys:
        holes = [Polygon(h).buffer(-COUNTER / 2, 16).buffer(COUNTER / 2, 16) for h in p.interiors]
        holes = [h for h in holes if not h.is_empty]
        out.append(Polygon(p.exterior).difference(unary_union(holes)) if holes else Polygon(p.exterior))
    return unary_union(out)


def draw():
    glyph = _fill(CONTOURS)
    if THICKEN:
        glyph = glyph.buffer(THICKEN, 16)
    glyph = glyph.buffer(CLOSE, 16).buffer(-CLOSE, 16).buffer(-ROUND, 16).buffer(ROUND, 16)
    return affinity.scale(_open_counters(glyph), SCALE, SCALE, origin=(0, 0))


